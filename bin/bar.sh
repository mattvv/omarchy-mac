#!/usr/bin/env bash
# Bar position and transparency, applied now and remembered for next time.
#
# `sketchybar --bar position=bottom` takes effect immediately and is forgotten
# on the next reload, because sketchybarrc sets position from its own file. So
# the choice is written to a state file that sketchybarrc sources -- the same
# shape as the generated theme.sh.
set -uo pipefail
STATE="$HOME/.local/state/omarchy-mac/bar.sh"
SKETCHYBAR=$(command -v sketchybar || echo /opt/homebrew/bin/sketchybar)

read_state() {
  BAR_POSITION=top; BAR_ALPHA=ff
  # shellcheck disable=SC1090
  [ -f "$STATE" ] && . "$STATE"
}

write_state() {
  mkdir -p "$(dirname "$STATE")"
  cat > "$STATE" <<EOF
# Generated by bar.sh -- do not edit.
export BAR_POSITION="$BAR_POSITION"
export BAR_ALPHA="$BAR_ALPHA"
EOF
}

apply() {
  # theme.sh owns the colour; this only swaps its alpha byte.
  # shellcheck disable=SC1090
  . "$HOME/.config/sketchybar/theme.sh" 2>/dev/null
  local rgb="${BG:-0xff101315}"
  rgb="0x${BAR_ALPHA}${rgb: -6}"
  "$SKETCHYBAR" --bar position="$BAR_POSITION" color="$rgb" >/dev/null 2>&1
}

read_state
case "${1:-status}" in
  status)   echo "position=$BAR_POSITION alpha=$BAR_ALPHA" ;;
  top|bottom)      BAR_POSITION="$1"; write_state; apply; echo "bar -> $1" ;;
  solid)           BAR_ALPHA=ff; write_state; apply; echo "bar -> solid" ;;
  translucent)     BAR_ALPHA=cc; write_state; apply; echo "bar -> translucent" ;;
  transparent)     BAR_ALPHA=66; write_state; apply; echo "bar -> transparent" ;;
  is-position)     [ "$BAR_POSITION" = "${2:-}" ] ;;
  is-alpha)        [ "$BAR_ALPHA" = "${2:-}" ] ;;
  *) echo "usage: bar.sh [status|top|bottom|solid|translucent|transparent]" >&2; exit 2 ;;
esac
