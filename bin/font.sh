#!/usr/bin/env bash
# Terminal font, written where the configs already look.
#
# Same rule the theme follows: never rewrite a config, generate a file it
# includes. ghostty/config has `config-file = ?"font.conf"` and wezterm dofiles
# wezterm-font.lua, so both end up on the same family without either file being
# edited by hand.
set -uo pipefail
GHOSTTY="$HOME/.config/ghostty/font.conf"
WEZTERM="$HOME/.config/wezterm-font.lua"

case "${1:-current}" in
  current)
    [ -f "$GHOSTTY" ] && sed -n 's/^font-family = "\(.*\)"$/\1/p' "$GHOSTTY" || true ;;
  set)
    family="${2:-}"
    [ -n "$family" ] || { echo "usage: font.sh set <family>" >&2; exit 2; }
    mkdir -p "$(dirname "$GHOSTTY")"
    printf '# Generated by font.sh -- do not edit.\nfont-family = "%s"\n' "$family" > "$GHOSTTY"
    printf -- '-- Generated by font.sh -- do not edit.\nreturn "%s"\n' "$family" > "$WEZTERM"
    # WezTerm watches its main config but not files it dofiles, so nudge it.
    [ -f "$HOME/.wezterm.lua" ] && touch "$HOME/.wezterm.lua"
    echo "$family" ;;
  *) echo "usage: font.sh [current|set <family>]" >&2; exit 2 ;;
esac
